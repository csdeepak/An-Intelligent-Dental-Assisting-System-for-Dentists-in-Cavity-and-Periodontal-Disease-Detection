#!/usr/bin/env python
"""
Evaluate the frozen bone-loss binary model on the rebuilt, non-jittered validation crops:
geometry check, calibration, PR curve and a cluster-bootstrap CI, in one pass.

WHAT THIS UNBLOCKS
------------------
Three `PAPER_MATERIAL.md` §9 items were stuck for want of bone-loss crops on this machine --
calibration (reliability diagram), a PR/threshold sweep, and confidence intervals. The crops are
now regenerated by `scripts/tufts/rebuild_bone_loss_crops.py`.

READ THIS BEFORE QUOTING ANY NUMBER FROM HERE
----------------------------------------------
The reported **0.9233 macro-F1** was measured on all 1,558 val crops, **49.6% of which carry
±15% coordinate jitter applied with offsets that were never saved**. Those crops cannot be
regenerated, so that figure cannot be reproduced here and this script does not claim to.
It evaluates the **785 deterministic non-jittered crops (750 normal / 35 diseased)** and reports
a NEW measurement on a clean subset. The two are different populations and must not be compared
as if one reproduced the other.

The geometry check is the first thing printed. The crops were rebuilt from `teeth_bbox.json` with
the documented 1.5x/2.0x expansion, against the radiograph directory chosen by *measurement*
(`_tufts_align.pick_image_dir`). If that geometry were wrong -- a 180° orientation error is the
failure that voided the R1 run -- the frozen model's discrimination would collapse toward chance.
Performance in the documented ballpark is therefore evidence the rebuild is sound; it is not a
reproduction claim.

**35 positives.** Every positive-class figure here rests on 35 teeth. Intervals are wide on
purpose and the support count is printed next to every number.

Usage:
    python scripts/eval/bone_loss_eval.py
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

DEF_MAN = REPO_ROOT / "data/tufts/bone_loss_crops_rebuilt/manifest_val.csv"
DEF_WEIGHTS = REPO_ROOT / "models/03_bone_loss_model_training_notebook_models/bone_loss_resnet18_best.pth"
DEF_OUT = REPO_ROOT / "outputs/bone_loss_eval"
DEF_FIG = REPO_ROOT / "docs/results/figures/paper"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, default=DEF_MAN)
    ap.add_argument("--weights", type=Path, default=DEF_WEIGHTS)
    ap.add_argument("--n-boot", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", type=Path, default=DEF_OUT)
    ap.add_argument("--fig", type=Path, default=DEF_FIG)
    args = ap.parse_args()

    import cv2
    import numpy as np
    import pandas as pd
    import torch
    from sklearn.metrics import (average_precision_score, confusion_matrix, f1_score,
                                 precision_recall_curve)
    from torchvision import transforms

    from src.classifiers import BONE_LOSS_CLASSES, IMAGENET_MEAN, IMAGENET_STD, load_classifier

    man = pd.read_csv(args.manifest)
    device = torch.device("cpu")
    model, cls = load_classifier(args.weights, 2, device)
    print(f"checkpoint class_to_idx: {cls}   module order: {BONE_LOSS_CLASSES}")
    # The bone-loss checkpoints are raw state_dicts with no class_to_idx; the order is
    # corroborated in models/03_.../run_summary.txt (alpha ratio 3.5171 vs count ratio 3.5162,
    # and the training summary's own "F1 Normal (cls 0)"). Index 1 is bone_loss.
    pos = 1

    tf = transforms.Compose([transforms.ToTensor(),
                             transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD)])
    probs, ys, groups, batch = [], [], [], []
    for i, r in man.iterrows():
        img = cv2.imread(str(REPO_ROOT / r["path"]), cv2.IMREAD_COLOR)
        if img is None:
            raise SystemExit(f"cannot read {r['path']}")
        img = cv2.resize(img, (224, 224), interpolation=cv2.INTER_LINEAR)
        batch.append(tf(cv2.cvtColor(img, cv2.COLOR_BGR2RGB)))
        ys.append(int(r["label"]))
        groups.append(str(r["stem"]))
        if len(batch) == 64 or i == len(man) - 1:
            with torch.no_grad():
                p = torch.softmax(model(torch.stack(batch).to(device)), dim=1).cpu().numpy()
            probs.extend(p[:, pos].tolist())
            batch = []

    p = np.array(probs); y = np.array(ys); g = np.array(groups)
    pred = (p >= 0.5).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    macro = float(f1_score(y, pred, average="macro"))
    sens = float(tp / (tp + fn)) if tp + fn else 0.0
    spec = float(tn / (tn + fp)) if tn + fp else 0.0

    print("\n=== GEOMETRY CHECK (this is not a reproduction claim) ===")
    print(f"  rebuilt non-jittered val: n={len(y)}  ({(y == 0).sum()} normal / {(y == 1).sum()} diseased)")
    print(f"  macro-F1     {macro:.4f}")
    print(f"  sensitivity  {sens:.4f}   (support {int(tp + fn)})")
    print(f"  specificity  {spec:.4f}   (support {int(tn + fp)})")
    print(f"  confusion    TN={tn} FP={fp} FN={fn} TP={tp}")
    print("  documented full val (1,558, incl. irreproducible jittered):"
          " macro-F1 0.9233, sens 0.8305, spec 0.9953")
    verdict = ("consistent -- geometry sound" if spec > 0.90 and sens > 0.50
               else "DIVERGENT -- suspect crop geometry, do not use these crops")
    print(f"  verdict: {verdict}")

    # ---------------------------------------------------------------- calibration + PR
    bins = 10
    edges = np.linspace(0, 1, bins + 1)
    idx = np.clip(np.digitize(p, edges) - 1, 0, bins - 1)
    ece = mce = 0.0
    rel = []
    for b in range(bins):
        m = idx == b
        if not m.any():
            rel.append(None)
            continue
        conf, obs, n = float(p[m].mean()), float(y[m].mean()), int(m.sum())
        ece += n / len(p) * abs(conf - obs)
        mce = max(mce, abs(conf - obs))
        rel.append((conf, obs, n))
    brier = float(np.mean((p - y) ** 2))
    ap_score = float(average_precision_score(y, p))
    pr, rc, _ = precision_recall_curve(y, p)

    # cluster bootstrap by SOURCE IMAGE -- teeth from one radiograph are not independent
    rng = np.random.default_rng(args.seed)
    uniq = np.unique(g)
    draws_ap, draws_sens, draws_f1 = [], [], []
    for _ in range(args.n_boot):
        pick = rng.choice(uniq, len(uniq), replace=True)
        sel = np.concatenate([np.flatnonzero(g == u) for u in pick])
        ys_, ps_ = y[sel], p[sel]
        if len(np.unique(ys_)) < 2:
            continue
        draws_ap.append(average_precision_score(ys_, ps_))
        pr_ = (ps_ >= 0.5).astype(int)
        draws_f1.append(f1_score(ys_, pr_, average="macro"))
        tp_ = int(((pr_ == 1) & (ys_ == 1)).sum()); fn_ = int(((pr_ == 0) & (ys_ == 1)).sum())
        if tp_ + fn_:
            draws_sens.append(tp_ / (tp_ + fn_))

    def ci(d):
        return [round(float(np.percentile(d, 2.5)), 4), round(float(np.percentile(d, 97.5)), 4)] if d else None

    print("\n=== CALIBRATION (never measured for this branch before) ===")
    print(f"  ECE {ece:.4f}   MCE {mce:.4f}   Brier {brier:.4f}")
    print(f"  average precision {ap_score:.4f}   CI95 {ci(draws_ap)}   (chance = {y.mean():.4f})")
    print(f"  macro-F1     CI95 {ci(draws_f1)}")
    print(f"  sensitivity  CI95 {ci(draws_sens)}   <- 35 positives, expect it to be wide")

    sweep = []
    for t in np.round(np.arange(0.05, 1.0, 0.05), 2):
        q = p >= t
        tp_ = int((q & (y == 1)).sum()); fp_ = int((q & (y == 0)).sum()); fn_ = int((~q & (y == 1)).sum())
        prec = tp_ / (tp_ + fp_) if tp_ + fp_ else None
        recl = tp_ / (tp_ + fn_) if tp_ + fn_ else None
        sweep.append({"threshold": float(t), "n_flagged": int(q.sum()),
                      "precision": round(prec, 4) if prec is not None else None,
                      "recall": round(recl, 4) if recl is not None else None})

    res = {"n": int(len(y)), "n_positive": int(y.sum()), "subset": "non-jittered val only",
           "not_a_reproduction_of": "0.9233 macro-F1 on the full 1,558 val crops",
           "macro_f1": round(macro, 4), "macro_f1_ci95": ci(draws_f1),
           "sensitivity": round(sens, 4), "sensitivity_ci95": ci(draws_sens),
           "specificity": round(spec, 4),
           "confusion": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
           "ece": round(ece, 4), "mce": round(mce, 4), "brier": round(brier, 4),
           "average_precision": round(ap_score, 4), "average_precision_ci95": ci(draws_ap),
           "prevalence": round(float(y.mean()), 4),
           "ci_method": f"cluster bootstrap over {len(uniq)} source images, "
                        f"{args.n_boot} resamples, seed {args.seed}",
           "threshold_sweep": sweep, "geometry_verdict": verdict}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "bone_loss_val_nonjittered.json").write_text(json.dumps(res, indent=2) + "\n")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, axx = plt.subplots(1, 2, figsize=(11, 4.6))
        axx[0].plot([0, 1], [0, 1], "--", color="grey", lw=1, label="perfect calibration")
        pts = [v for v in rel if v]
        axx[0].plot([c for c, _, _ in pts], [o for _, o, _ in pts], "o-", color="#6a4c93",
                    label="bone-loss binary")
        axx[0].set_xlabel("mean predicted P(bone loss)"); axx[0].set_ylabel("observed fraction")
        axx[0].set_title(f"Reliability — rebuilt val (n={len(y)}, {int(y.sum())} pos)\n"
                         f"ECE {ece:.3f} · Brier {brier:.3f}")
        axx[0].legend(fontsize=8); axx[0].set_xlim(0, 1); axx[0].set_ylim(0, 1)
        axx[1].plot(rc, pr, color="#1d3557")
        axx[1].axhline(float(y.mean()), ls="--", color="grey", lw=1,
                       label=f"chance = prevalence {y.mean():.3f}")
        axx[1].set_xlabel("recall"); axx[1].set_ylabel("precision")
        axx[1].set_title(f"Precision–Recall — AP {ap_score:.3f}")
        axx[1].legend(fontsize=8); axx[1].set_xlim(0, 1); axx[1].set_ylim(0, 1)
        fig.tight_layout()
        args.fig.mkdir(parents=True, exist_ok=True)
        fp_ = args.fig / "bone_loss_calibration_val.png"
        fig.savefig(fp_, dpi=160)
        print(f"\n  figure -> {fp_}")
    except Exception as exc:
        print(f"  (figure skipped: {exc})")

    print(f"-> {args.out / 'bone_loss_val_nonjittered.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
